-- زمینه: از بین سه کانال «اخبار حوزه» (migration_028)، فید رسا از قبل
-- فقط سیاسیه ولی فیدهای حوزه‌خراسان/حوزه‌نیوز عمومی‌ان (همه‌ی موضوعات:
-- دینی/فرهنگی/سیاسی/اجتماعی/...). طبق درخواست کاربر، هوش مصنوعی
-- (Edge Function extract-post-keywords، همون پاس موجود هر ۲ ساعته)
-- هر پستِ کانال‌های show_in_hawza=true رو بررسی می‌کنه و این ستون رو
-- پر می‌کنه — تب «اخبار حوزه» فقط پست‌های hawza_relevant=true رو نشون
-- می‌ده.
--
-- NULL = هنوز بررسی‌نشده (پست‌های تازه‌ی کانال‌های غیرحوزه هم برای
-- همیشه NULL می‌مونن، چون هیچ‌جا خونده نمی‌شه — بی‌ضرره)؛ true/false =
-- نتیجه‌ی قطعی هوش مصنوعی، دیگه دوباره بررسی نمی‌شه.
-- =====================================================================

alter table posts add column if not exists hawza_relevant boolean;
