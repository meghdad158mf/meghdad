-- =====================================================================
-- جریان — مهاجرت ۰۳۰: View شمارش یکتای روزنامه‌ها (رفع سقف ۱۰۰۰ردیفی)
-- این فایل را کامل در Supabase SQL Editor پیست و اجرا کنید.
-- ایمن برای اجرای چندباره (idempotent).
--
-- زمینه: کاشی «خبرگزاری» صفحه‌ی نخست (renderDashHeroStats) تعداد
-- کانال‌های show_in_news رو با تعداد عنوان‌های یکتای جدول newspapers
-- جمع می‌زنه. برای گرفتن عنوان‌های یکتا، فرانت‌اند قبلاً کل ستون slug
-- رو با select=slug&limit=5000 می‌گرفت و خودش توی جاوااسکریپت با Set
-- یکتا می‌کرد — ولی «Max Rows» سطح API سوپابیس (پیش‌فرض ۱۰۰۰) هر پاسخ
-- رو به ۱۰۰۰ ردیف واقعی محدود می‌کنه، مستقل از limit خودِ کلاینت. تا
-- وقتی کل جدول newspapers زیر ۱۰۰۰ ردیف بود مشکلی نبود؛ وقتی رد شد،
-- فقط قدیمی‌ترین ۱۰۰۰ ردیف (بدون order صریح) برمی‌گشت و عنوان‌های
-- یکتای جدیدتر از شمارش جا می‌موندن — نتیجه: عدد کاشی «خبرگزاری»
-- به‌طرز نامحسوسی و روزبه‌روز بیشتر از واقعیت کمتر نشون داده می‌شد.
--
-- راه‌حل: یکتاسازی رو به خودِ دیتابیس بسپاریم (این View) و فقط *تعداد*
-- رو با همون ترفند Content-Range (بدون انتقال ردیف‌های واقعی، پس بدون
-- برخورد به سقف Max Rows) بگیریم — دقیقاً همون الگوی fetchExactCount
-- که برای «محتوای رصد شده» از قبل استفاده می‌شه.
-- =====================================================================

create or replace view newspaper_unique_slugs as
  select distinct slug from newspapers;

grant select on newspaper_unique_slugs to app_admin, app_viewer;
